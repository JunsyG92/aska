    assert.equal(notes[0].title, 'Claude replied');
    // Start of the answer, as plain text (the fake Claude resumes its session here).
    assert.equal(notes[0].body, 'Session continued: preload.js exposes a minimal API.');
    await toggle();
    await page.waitForTimeout(400);
    assert.equal(await visible(), true);
    assert.equal(await page.locator('.panel.has-unread').count(), 0, 'reply read once the chat is reopened');
    assert.equal(await turns(), 8);
    // Minimized to a pill while working: notification, and the pill flags the reply.
