#!/usr/bin/env bash
# Installs Aska for the current user (no sudo):
#   launcher ~/.local/bin/aska, menu entry, background autostart.
# Options:
#   --gnome-shortcut   registers Ctrl+Alt+Space -> "aska --toggle" in GNOME (useful on Wayland)
#   --no-autostart     does not start Aska when you log in
#   --sandbox-fix      (Ubuntu 24.04+) installs the sandbox AppArmor profile without asking
#   --no-sandbox-fix   leaves the system untouched: the command to run is only printed
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# macOS: dedicated installation (Electron.app, LaunchAgent, Aska.app).
[ "$(uname -s)" = Darwin ] && exec "$ROOT/scripts/install-macos.sh" "$@"
GNOME=0; AUTOSTART=1; SANDBOX_FIX=ask
for a in "$@"; do
  case "$a" in
    --gnome-shortcut) GNOME=1 ;;
    --no-autostart) AUTOSTART=0 ;;
    --sandbox-fix) SANDBOX_FIX=yes ;;
    --no-sandbox-fix) SANDBOX_FIX=no ;;
    *) echo "Unknown option: $a" >&2; exit 2 ;;
  esac
done

command -v node >/dev/null || { echo "Node.js (>= 20) is required." >&2; exit 1; }
ELECTRON="$ROOT/node_modules/electron/dist/electron"
[ -d "$ROOT/node_modules/electron" ] || (cd "$ROOT" && npm install --no-fund --no-audit)
# Electron >= 45 no longer downloads its binary during "npm install": we do it here.
if [ ! -x "$ELECTRON" ]; then
  echo "Downloading Electron (about 100 MB)..."
  node "$ROOT/node_modules/electron/install.js" || {
    cat >&2 <<MSG

Downloading Electron failed (see the error above). Common causes:
  - no access to github.com (network, proxy or firewall);
  - proxy: export HTTPS_PROXY (and ELECTRON_GET_USE_PROXY=1) then run again;
  - mirror: ELECTRON_MIRROR=https://npmmirror.com/mirrors/electron/ ./scripts/install.sh
MSG
    exit 1
  }
fi
[ -x "$ELECTRON" ] || { echo "Electron not found after installation ($ELECTRON)." >&2; exit 1; }

BIN="${XDG_BIN_HOME:-$HOME/.local/bin}"
APPS="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
CONF="${XDG_CONFIG_HOME:-$HOME/.config}"
mkdir -p "$BIN" "$APPS"

cat > "$BIN/aska" <<LAUNCHER
#!/bin/sh
# Aska launcher (generated by scripts/install.sh).
# Help and version: answered in the terminal, without starting the UI.
for ARG in "\$@"; do
  case "\$ARG" in
    -h|--help|-v|-V|--version)
      if command -v node >/dev/null; then exec node "$ROOT/src/cli.js" "\$@"; fi
      ELECTRON_RUN_AS_NODE=1 exec "$ELECTRON" "$ROOT/src/cli.js" "\$@" ;;
  esac
done
SANDBOX="$ROOT/node_modules/electron/dist/chrome-sandbox"
# Ubuntu 24.04+: without an AppArmor profile or setuid helper, Electron stops
# abruptly (SIGTRAP). We explain it rather than crash silently.
if [ "\$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null)" = 1 ] \\
   && [ ! -e /etc/apparmor.d/aska ] \\
   && [ "\$(stat -c '%U:%a' "\$SANDBOX" 2>/dev/null)" != "root:4755" ]; then
  MSG="The Electron sandbox is not configured on this system. Run again: $ROOT/scripts/install.sh --sandbox-fix"
  echo "\$MSG" >&2
  command -v notify-send >/dev/null && notify-send "Aska cannot start" "\$MSG"
  exit 1
fi
exec "$ELECTRON" "$ROOT" "\$@"
LAUNCHER
chmod 755 "$BIN/aska"

desktop() { # $1 = file, $2 = arguments
  cat > "$1" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Aska
Comment=Ask an AI agent to do something (Claude, Codex, Copilot, Cursor)
Exec="$BIN/aska" $2
Icon=$ROOT/assets/aska.svg
Terminal=false
Categories=Utility;Development;
StartupNotify=false
DESKTOP
}
desktop "$APPS/aska.desktop" "--toggle"
if [ "$AUTOSTART" = 1 ]; then
  mkdir -p "$CONF/autostart"
  desktop "$CONF/autostart/aska.desktop" "--hidden"
fi

# Private configuration: it decides which programs are run, hence 0600.
( umask 077; mkdir -p "$CONF/aska" )
chmod 700 "$CONF/aska"
if [ ! -e "$CONF/aska/config.json" ]; then
  if [ "$GNOME" = 1 ]; then SHORTCUT=false; else SHORTCUT='"Control+Alt+Space"'; fi
  ( umask 077; cat > "$CONF/aska/config.json" <<JSON
{
  "shortcut": $SHORTCUT,
  "defaultAgent": "claude",
  "defaultMode": "read",
  "allowAutoMode": false
}
JSON
  )
fi
chmod 600 "$CONF/aska/config.json"

if [ "$GNOME" = 1 ]; then
  if command -v gsettings >/dev/null; then
    SCHEMA=org.gnome.settings-daemon.plugins.media-keys
    KEY=/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/aska/
    LIST="$(gsettings get $SCHEMA custom-keybindings)"
    case "$LIST" in
      *"$KEY"*) ;;
      "@as []"|"[]") gsettings set $SCHEMA custom-keybindings "['$KEY']" ;;
      *) gsettings set $SCHEMA custom-keybindings "${LIST%]}, '$KEY']" ;;
    esac
    gsettings set "$SCHEMA.custom-keybinding:$KEY" name 'Aska'
    gsettings set "$SCHEMA.custom-keybinding:$KEY" command "$BIN/aska --toggle"
    gsettings set "$SCHEMA.custom-keybinding:$KEY" binding '<Control><Alt>space'
    echo "GNOME shortcut registered: Ctrl+Alt+Space"
  else
    echo "gsettings not found: bind \"$BIN/aska --toggle\" to a shortcut in your keyboard settings." >&2
  fi
fi

# The Chromium sandbox must stay enabled. Ubuntu 24.04+ forbids by default
# the unprivileged namespaces it needs: the method recommended
# by Ubuntu is an AppArmor profile that allows them for this binary only.
RESTRICT="$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null || echo 0)"
PROFILE=/etc/apparmor.d/aska
SANDBOX="$ROOT/node_modules/electron/dist/chrome-sandbox"
REAL_ELECTRON="$(readlink -f "$ELECTRON")"
if [ "$RESTRICT" = 1 ]; then
  WANT="$(printf '%s\n' \
    '# Aska: allows Electron to create the namespaces of its sandbox.' \
    '# Generated by scripts/install.sh, safe to remove (sudo rm /etc/apparmor.d/aska).' \
    'abi <abi/4.0>,' \
    'include <tunables/global>' \
    '' \
    "profile aska \"$REAL_ELECTRON\" flags=(unconfined) {" \
    '  userns,' \
    '  include if exists <local/aska>' \
    '}')"
  if [ -e "$PROFILE" ] && [ "$(cat "$PROFILE")" = "$WANT" ]; then
    : # already in place for this folder
  else
    APPLY=no
    if [ "$SANDBOX_FIX" = yes ]; then
      APPLY=yes
    elif [ "$SANDBOX_FIX" = ask ] && [ -t 0 ]; then
      echo
      echo "Ubuntu 24.04+ blocks the Electron sandbox. For Aska to start, this script"
      echo "can install an AppArmor profile in $PROFILE (asks for your sudo password)."
      printf "Install it now? [Y/n] "
      read -r REPLY
      case "$REPLY" in [nN]*) ;; *) APPLY=yes ;; esac
    fi
    if [ "$APPLY" = yes ] && command -v apparmor_parser >/dev/null; then
      TMP="$(mktemp)"
      printf '%s\n' "$WANT" > "$TMP"
      if sudo install -m 644 -o root -g root "$TMP" "$PROFILE" && sudo apparmor_parser -r "$PROFILE"; then
        echo "AppArmor profile installed: the Electron sandbox is enabled."
      else
        echo "Installing the AppArmor profile failed." >&2
        APPLY=failed
      fi
      rm -f "$TMP"
    fi
    if [ "$APPLY" != yes ]; then
      cat <<MSG

Ubuntu 24.04+ blocks the Electron sandbox: Aska will not start until
this is fixed. Either:
  - run this script again with: ./scripts/install.sh --sandbox-fix   (recommended)
  - or, to redo after every "npm install":
      sudo chown root:root "$SANDBOX" && sudo chmod 4755 "$SANDBOX"
MSG
    fi
  fi
fi

echo
echo "Aska is installed. Run \"aska\" (or \"aska --hidden\" in the background), then press Ctrl+Alt+Space."
case ":$PATH:" in *":$BIN:"*) ;; *) echo "Note: add $BIN to your PATH." ;; esac
