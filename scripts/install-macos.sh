#!/usr/bin/env bash
# Installs Aska on macOS for the current user (no sudo):
#   launcher ~/.local/bin/aska, app ~/Applications/Aska.app (Spotlight, Launchpad),
#   background autostart (LaunchAgent).
# Called by scripts/install.sh on macOS. Options:
#   --no-autostart     does not start Aska when you log in
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
AUTOSTART=1
for a in "$@"; do
  case "$a" in
    --no-autostart) AUTOSTART=0 ;;
    --gnome-shortcut|--sandbox-fix|--no-sandbox-fix) ;; # Linux options, no effect here
    *) echo "Unknown option: $a" >&2; exit 2 ;;
  esac
done

command -v node >/dev/null || { echo "Node.js (>= 20) is required (brew install node)." >&2; exit 1; }
ELECTRON="$ROOT/node_modules/electron/dist/Electron.app/Contents/MacOS/Electron"
[ -d "$ROOT/node_modules/electron" ] || (cd "$ROOT" && npm install --no-fund --no-audit)
# Electron >= 45 no longer downloads its binary during "npm install": we do it here.
if [ ! -x "$ELECTRON" ]; then
  echo "Downloading Electron (about 100 MB)..."
  node "$ROOT/node_modules/electron/install.js" || {
    cat >&2 <<MSG

Downloading Electron failed (see the error above). Common causes:
  - no access to github.com (network, proxy or firewall);
  - proxy: export HTTPS_PROXY (and ELECTRON_GET_USE_PROXY=1) then run again;
  - mirror: ELECTRON_MIRROR=https://npmmirror.com/mirrors/electron/ ./scripts/install.sh
MSG
    exit 1
  }
fi
[ -x "$ELECTRON" ] || { echo "Electron not found after installation ($ELECTRON)." >&2; exit 1; }

BIN="${XDG_BIN_HOME:-$HOME/.local/bin}"
CONF="${XDG_CONFIG_HOME:-$HOME/.config}"
APP="$HOME/Applications/Aska.app"
AGENT="$HOME/Library/LaunchAgents/io.github.aska.plist"
mkdir -p "$BIN"

cat > "$BIN/aska" <<LAUNCHER
#!/bin/sh
# Aska launcher (generated by scripts/install-macos.sh).
# Help and version: answered in the terminal, without starting the UI.
for ARG in "\$@"; do
  case "\$ARG" in
    -h|--help|-v|-V|--version)
      if command -v node >/dev/null; then exec node "$ROOT/src/cli.js" "\$@"; fi
      ELECTRON_RUN_AS_NODE=1 exec "$ELECTRON" "$ROOT/src/cli.js" "\$@" ;;
  esac
done
exec "$ELECTRON" "$ROOT" "\$@"
LAUNCHER
chmod 755 "$BIN/aska"

# Small app that calls the launcher: Aska shows up in Spotlight and Launchpad.
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cat > "$APP/Contents/MacOS/Aska" <<APPRUN
#!/bin/sh
exec "$BIN/aska" --toggle
APPRUN
chmod 755 "$APP/Contents/MacOS/Aska"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Aska</string>
  <key>CFBundleDisplayName</key><string>Aska</string>
  <key>CFBundleIdentifier</key><string>io.github.aska.launcher</string>
  <key>CFBundleExecutable</key><string>Aska</string>
  <key>CFBundleIconFile</key><string>Aska</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$(node -p "require('$ROOT/package.json').version")</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
PLIST
# Icon: SVG rendered by Quick Look, then an .icns size set (optional).
ICON_TMP="$(mktemp -d)"
if qlmanage -t -s 1024 -o "$ICON_TMP" "$ROOT/assets/aska.svg" >/dev/null 2>&1 && [ -f "$ICON_TMP/aska.svg.png" ]; then
  SET="$ICON_TMP/Aska.iconset"
  mkdir -p "$SET"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$ICON_TMP/aska.svg.png" --out "$SET/icon_${s}x${s}.png" >/dev/null
    sips -z $((s * 2)) $((s * 2)) "$ICON_TMP/aska.svg.png" --out "$SET/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$SET" -o "$APP/Contents/Resources/Aska.icns" 2>/dev/null || true
fi
rm -rf "$ICON_TMP"

# Start at login, in the background.
if [ "$AUTOSTART" = 1 ]; then
  mkdir -p "$(dirname "$AGENT")"
  cat > "$AGENT" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>io.github.aska</string>
  <key>ProgramArguments</key>
  <array>
    <string>$BIN/aska</string>
    <string>--hidden</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>ProcessType</key><string>Interactive</string>
</dict>
</plist>
PLIST
else
  rm -f "$AGENT"
fi

# Private configuration: it decides which programs are run, hence 0600.
( umask 077; mkdir -p "$CONF/aska" )
chmod 700 "$CONF/aska"
if [ ! -e "$CONF/aska/config.json" ]; then
  ( umask 077; cat > "$CONF/aska/config.json" <<JSON
{
  "shortcut": "Control+Alt+Space",
  "defaultAgent": "claude",
  "defaultMode": "read",
  "allowAutoMode": false
}
JSON
  )
fi
chmod 600 "$CONF/aska/config.json"

echo
echo "Aska is installed. Run \"aska\" (or open Aska from Spotlight), then press ⌃⌥Space (Ctrl+Option+Space)."
case ":$PATH:" in
  *":$BIN:"*) ;;
  *) echo "Note: $BIN is not in your PATH. Add it: echo 'export PATH=\"$BIN:\$PATH\"' >> ~/.zshrc" ;;
esac
